-- Chitral Tourism Explorer database setup
-- Run this in the chitral_tourism_db database using pgAdmin Query Tool.
-- This creates the schema/table if missing; it does not delete existing data.

CREATE EXTENSION IF NOT EXISTS postgis;

CREATE TABLE IF NOT EXISTS public.tourist_attractions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    category TEXT,
    description TEXT,
    latitude DOUBLE PRECISION,
    longitude DOUBLE PRECISION,
    elevation_m INTEGER,
    accessibility TEXT,
    best_visit_season TEXT,
    geom geometry(Point, 4326),
    coordinate_source TEXT,
    coordinate_status TEXT,
    osm_display_name TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT tourist_attractions_latitude_check
        CHECK (latitude IS NULL OR latitude BETWEEN -90 AND 90),
    CONSTRAINT tourist_attractions_longitude_check
        CHECK (longitude IS NULL OR longitude BETWEEN -180 AND 180)
);

-- Prevent duplicate attraction names regardless of capitalization.
CREATE UNIQUE INDEX IF NOT EXISTS tourist_attractions_name_lower_uidx
ON public.tourist_attractions (LOWER(name));

CREATE INDEX IF NOT EXISTS tourist_attractions_category_idx
ON public.tourist_attractions (category);

CREATE INDEX IF NOT EXISTS tourist_attractions_geom_gix
ON public.tourist_attractions USING GIST (geom);

-- Check table and PostGIS.
SELECT
    current_database() AS database_name,
    PostGIS_Full_Version() AS postgis_version,
    COUNT(*) AS existing_attractions
FROM public.tourist_attractions;
